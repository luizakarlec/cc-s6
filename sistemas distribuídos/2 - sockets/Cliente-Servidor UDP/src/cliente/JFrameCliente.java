    private void btnChaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChaveActionPerformed
        String nome = txtNome.getText().trim();
        String email = txtEmail.getText().trim();

        if (nome.isEmpty() || email.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha nome e e-mail");
            return;
        }

        Pessoa p = new Pessoa(nome, email);

        try {
            Cliente c = new Cliente(p);
            txtChave.setText(c.getResposta());
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Erro de comunicação: " + ex.getMessage());
        }
        
    }//GEN-LAST:event_btnChaveActionPerformed

